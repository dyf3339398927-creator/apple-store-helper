let currentLang = 'zh';

function setLanguage(lang){
  currentLang = lang;
  document.documentElement.lang = lang;
  if(translations[lang] && translations[lang].page_title){
    document.title = translations[lang].page_title;
  }
  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const key = el.getAttribute('data-i18n');
    if(translations[lang] && translations[lang][key]){
      el.innerHTML = translations[lang][key];
    }
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el=>{
    const key = el.getAttribute('data-i18n-ph');
    if(translations[lang] && translations[lang][key]){
      el.setAttribute('placeholder', translations[lang][key]);
    }
  });
  document.querySelectorAll('.lang-btn').forEach(btn=>{
    btn.classList.toggle('active', btn.getAttribute('data-lang')===lang);
  });
  localStorage.setItem('ritah_lang', lang);
}

document.querySelectorAll('.lang-btn').forEach(btn=>{
  btn.addEventListener('click', ()=> setLanguage(btn.getAttribute('data-lang')));
});

const savedLang = localStorage.getItem('ritah_lang') || 'ja';
setLanguage(savedLang);

// ---- Inquiry form: submits to the RITAH International backend API ----
// Change API_BASE to your deployed API URL when hosting this site online.
const API_BASE = window.RITAH_API_BASE || 'http://localhost:3000';

const inquiryForm = document.getElementById('inquiryForm');
const formStatus = document.getElementById('formStatus');

if (inquiryForm) {
  inquiryForm.addEventListener('submit', async (e) => {
    e.preventDefault();
    const submitBtn = inquiryForm.querySelector('button[type="submit"]');
    const originalBtnText = submitBtn.textContent;

    const fd = new FormData(inquiryForm);
    const payload = {
      name: fd.get('name'),
      email: fd.get('email'),
      phone: fd.get('phone'),
      product: fd.get('product'),
      message: fd.get('message')
    };

    formStatus.textContent = '';
    formStatus.className = 'form-status';

    // Disable the button and show a loading state while the request is in flight
    submitBtn.disabled = true;
    submitBtn.style.opacity = '0.6';
    submitBtn.textContent = translations[currentLang].form_sending;

    try {
      const res = await fetch(`${API_BASE}/api/inquiries`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(payload)
      });
      const data = await res.json();
      if (res.ok) {
        formStatus.textContent = translations[currentLang].form_success;
        formStatus.classList.add('success');
        inquiryForm.reset();
      } else {
        formStatus.textContent = data.error || translations[currentLang].form_error;
        formStatus.classList.add('error');
      }
    } catch (err) {
      formStatus.textContent = translations[currentLang].form_error;
      formStatus.classList.add('error');
    } finally {
      // Restore the button
      submitBtn.disabled = false;
      submitBtn.style.opacity = '1';
      submitBtn.textContent = originalBtnText;
    }
  });
}
